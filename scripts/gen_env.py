import os
import secrets
from pathlib import Path

def generate_environment(env_file: str = ".env"):
    root_dir = Path(__file__).resolve().parent.parent
    target_env = root_dir / env_file
    keys_dir = root_dir / "docker" / "keys"
    keys_dir.mkdir(parents=True, exist_ok=True)

    postgres_pass = secrets.token_urlsafe(20)
    jwt_secret = secrets.token_urlsafe(32)
    admin_pass = secrets.token_urlsafe(16)
    analyst_pass = secrets.token_urlsafe(16)
    node_key_low = secrets.token_hex(24)
    node_key_med = secrets.token_hex(24)

    env_content = f"""# HoneyForge Production Environment Configuration
# Automatically generated by scripts/gen_env.py

# PostgreSQL Database Configuration
POSTGRES_DB=honeyforge
POSTGRES_USER=honeyforge
POSTGRES_PASSWORD={postgres_pass}
DATABASE_URL=postgresql+asyncpg://honeyforge:{postgres_pass}@db-store:5432/honeyforge

# JWT Authentication Secret
JWT_SECRET={jwt_secret}
ACCESS_TOKEN_EXPIRE_MINUTES=480

# Operator Credentials
ADMIN_PASSWORD={admin_pass}
ANALYST_PASSWORD={analyst_pass}

# Stealth Node Identifiers and Node Keys
NODE_LOW_ID=n-7f3a
NODE_KEY_LOW={node_key_low}

NODE_MED_ID=n-8c1b
NODE_KEY_MED={node_key_med}

# Server Network Bindings
HONEYFORGE_HOST=0.0.0.0
HONEYFORGE_PORT=8000
"""

    with open(target_env, "w", encoding="utf-8") as f:
        f.write(env_content)
    print(f"[+] Successfully wrote environment to {target_env}")

    # Write key secret files for volume mounting into containers
    key_low_path = keys_dir / "node_low.key"
    with open(key_low_path, "w", encoding="utf-8") as f:
        f.write(node_key_low.strip())
    print(f"[+] Successfully wrote key secret to {key_low_path}")

    key_med_path = keys_dir / "node_med.key"
    with open(key_med_path, "w", encoding="utf-8") as f:
        f.write(node_key_med.strip())
    print(f"[+] Successfully wrote key secret to {key_med_path}")
    print("\n" + "=" * 60)
    print(" [HoneyForge] Generated Operator Credentials:")
    print(f"  > ADMIN_PASSWORD   : {admin_pass}")
    print(f"  > ANALYST_PASSWORD : {analyst_pass}")
    print("=" * 60 + "\n")

if __name__ == "__main__":
    generate_environment()
